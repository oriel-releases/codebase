/** A random line, never the same as the previous one. */
export function randomQuote(previous?: number): { text: string; index: number } {
  let index = Math.floor(Math.random() * quotes.length);
  if (index === previous) index = (index + 1) % quotes.length;
  return { text: quotes[index], index };
}
