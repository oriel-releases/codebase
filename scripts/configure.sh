#!/usr/bin/env bash
# Writes Config/Secrets.xcconfig from UNSPLASH_ACCESS_KEY (environment, handy for CI) or .env,
# then regenerates Oriel.xcodeproj. Run it after cloning and whenever project.yml or .env changes.
set -euo pipefail
cd "$(dirname "$0")/.."

key="${UNSPLASH_ACCESS_KEY:-}"
if [[ -z "$key" && -f .env ]]; then
  key="$(grep -E '^[[:space:]]*UNSPLASH_ACCESS_KEY=' .env | tail -n 1 | cut -d= -f2- | tr -d '[:space:]"' || true)"
fi

if [[ -z "$key" ]]; then
  echo "warning: no Unsplash key: set UNSPLASH_ACCESS_KEY or add it to .env. The app will build but can't fetch photos." >&2
fi

cat > Config/Secrets.xcconfig <<EOF
// Generated by scripts/configure.sh. Do not commit.
UNSPLASH_ACCESS_KEY = $key
EOF

xcodegen generate --quiet
echo "Configured (Unsplash key: $([[ -n "$key" ]] && echo set || echo missing))"
