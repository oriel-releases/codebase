#!/usr/bin/env bash
# Writes Config/Secrets.xcconfig from UNSPLASH_ACCESS_KEY (environment, handy for CI) or .env,
# then regenerates Oriel.xcodeproj. Run it after cloning and whenever project.yml or .env changes.
set -euo pipefail
cd "$(dirname "$0")/.."

# A value from the environment, else from .env.
setting() {
  local value="${!1:-}"
  if [[ -z "$value" && -f .env ]]; then
    value="$(grep -E "^[[:space:]]*$1=" .env | tail -n 1 | cut -d= -f2- | tr -d '[:space:]"' || true)"
  fi
  echo "$value"
}

key="$(setting UNSPLASH_ACCESS_KEY)"
sparkle="$(setting SPARKLE_PUBLIC_KEY)"
pollinations="$(setting POLLINATIONS_KEY)"

if [[ -z "$pollinations" ]]; then
  echo "warning: no Pollinations key: set POLLINATIONS_KEY or add it to .env. The app will build but can't create AI wallpapers." >&2
fi
if [[ -z "$key" ]]; then
  echo "warning: no Unsplash key: set UNSPLASH_ACCESS_KEY or add it to .env. The app will build but can't fetch photos." >&2
fi

cat > Config/Secrets.xcconfig <<EOF
// Generated by scripts/configure.sh. Do not commit.
UNSPLASH_ACCESS_KEY = $key
SPARKLE_PUBLIC_KEY = $sparkle
POLLINATIONS_KEY = $pollinations
EOF

xcodegen generate --quiet
echo "Configured (Unsplash key: $([[ -n "$key" ]] && echo set || echo missing), Pollinations key: $([[ -n "$pollinations" ]] && echo set || echo missing))"
