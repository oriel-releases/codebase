/// A photo for an interest's tile (Unsplash, credited to its photographer).
struct Cover {
    var path: String
    var by: String

    /// `https://images.unsplash.com/{path}&w=…&h=…&fit=crop&q=70&fm=jpg` (each path already has `?ixid=…`).
    func url(width: Int = 480) -> URL {
        URL(string: "https://images.unsplash.com/\(path)&w=\(width)&h=\(width * 3 / 4)&fit=crop&q=70&fm=jpg")!
    }
}

